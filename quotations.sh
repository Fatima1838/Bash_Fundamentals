#!/bin/bash

# QUOTATIONS IN BASH
# Quotes are used to handle text strings.

# Double quotes allow variables
name="Fatima"
echo "Hello $name"

# Single quotes treat text literally
echo 'Hello $name'

# Common mistakes:
# Forgetting quotes around spaces in text

# Example:
echo "My name is Fatima"

# Troubleshooting:
# If variable doesn't work, use double quotes not single quotes.
